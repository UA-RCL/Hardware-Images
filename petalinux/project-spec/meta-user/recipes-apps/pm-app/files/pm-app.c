/*
 * pm-app -- userspace driver for the PE-array program manager on VCU128/MicroBlaze.
 *
 * program_manager_top is a free-running (ap_ctrl_none) HLS kernel with an
 * AXI-Lite slave and an AXI4-Stream instruction port: no ap_start to assert, no
 * interrupt to wait on. It begins evaluating the grid the moment reset releases.
 * All we do is write a command, strobe valid, and poll the busy bitmap.
 *
 * The register window is a plain mmap of /dev/mem at the IP's base address.
 * There is no interrupt, so UIO would buy nothing over this.
 *
 * Two runtime tables live in the manager and are uploaded from here at startup:
 * which cluster each PE belongs to, and which kernel is resident in each of its
 * banks. Instructions themselves do not come through this file's register
 * window -- they are DMA'd into the manager's stream port by dma.c.
 *
 * This mirrors the Alveo host in HW_prototype/boards/u280/host_runtime.cpp and
 * the C-simulation testbench in vitis_hls/program_manager/test/main_csim.cpp --
 * the occupancy map it prints should match what `make csim` prints for the same
 * sequence.
 */

